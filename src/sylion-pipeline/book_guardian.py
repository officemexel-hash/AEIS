def _run_tests() -> None:
    """Basic self-tests for BookGuardian."""
    import tempfile
    import unittest

    class TestBookGuardian(unittest.TestCase):

        def setUp(self):
            self.tmpdir = tempfile.mkdtemp()
            self.ksiega = Path(self.tmpdir) / "ksiega.docx"
            self.ksiega.write_bytes(b"Ksiega SYLION 3.4 FIXED content here")
            self.log_dir = Path(self.tmpdir) / "logs"

        def tearDown(self):
            import shutil
            shutil.rmtree(self.tmpdir, ignore_errors=True)

        def test_01_init_computes_baseline(self):
            g = BookGuardian(self.ksiega, log_dir=self.log_dir)
            self.assertIsNotNone(g.baseline)
            self.assertTrue(g.baseline.exists)
            self.assertTrue(len(g.baseline_sha) == 64)
            print(f"  ✓ test_01: baseline SHA={g.baseline_sha[:16]}")

        def test_02_check_ok_unchanged(self):
            g = BookGuardian(self.ksiega, log_dir=self.log_dir)
            self.assertTrue(g.check())
            self.assertTrue(g.is_healthy)
            self.assertEqual(g.drift_count, 0)
            print("  ✓ test_02: check OK when unchanged")

        def test_03_detect_modification(self):
            g = BookGuardian(self.ksiega, log_dir=self.log_dir)
            # Modify Księga
            self.ksiega.write_bytes(b"MODIFIED CONTENT -- drift!")
            self.assertFalse(g.check())
            self.assertFalse(g.is_healthy)
            self.assertEqual(g.drift_count, 1)
            print("  ✓ test_03: drift detected on modification")

        def test_04_detect_deletion(self):
            g = BookGuardian(self.ksiega, log_dir=self.log_dir)
            self.ksiega.unlink()
            self.assertFalse(g.check())
            self.assertFalse(g.is_healthy)
            print("  ✓ test_04: drift detected on deletion")

        def test_05_update_baseline(self):
            g = BookGuardian(self.ksiega, log_dir=self.log_dir)
            old_sha = g.baseline_sha
            self.ksiega.write_bytes(b"Authorized new content")
            new_snap = g.update_baseline(authorized_by="admin")
            self.assertNotEqual(old_sha, new_snap.sha256)
            self.assertTrue(g.check())  # Now OK with new baseline
            print("  ✓ test_05: baseline update works")

        def test_06_missing_file_at_init(self):
            missing = Path(self.tmpdir) / "nonexistent.docx"
            g = BookGuardian(missing, log_dir=self.log_dir)
            self.assertFalse(g.baseline.exists)
            self.assertTrue(g.check())  # No file = nothing to check
            print("  ✓ test_06: graceful handling of missing file")

        def test_07_persistence(self):
            g = BookGuardian(self.ksiega, log_dir=self.log_dir)
            # Check baseline file was written
            baseline_file = self.log_dir / "baseline.json"
            self.assertTrue(baseline_file.exists())
            with open(baseline_file) as f:
                data = json.load(f)
            self.assertEqual(data["sha256"], g.baseline_sha)
            print("  ✓ test_07: baseline persisted to disk")

        def test_08_export_report(self):
            g = BookGuardian(self.ksiega, log_dir=self.log_dir)
            g.check()
            report = g.export_report()
            self.assertEqual(report["agent_id"], "book_guardian")
            self.assertTrue(report["is_healthy"])
            self.assertEqual(report["check_count"], 1)
            print("  ✓ test_08: export_report works")

        def test_09_human_gate_escalation(self):
            """Test that drift triggers Human Gate (mock)."""
            escalated = []

            class MockGate:
                def request_approval(self, req):
                    escalated.append(req)
                    return req

            g = BookGuardian(
                self.ksiega, human_gate=MockGate(), log_dir=self.log_dir,
            )
            self.ksiega.write_bytes(b"UNAUTHORIZED CHANGE")
            g.check()
            self.assertEqual(len(escalated), 1)
            # Check it's CRITICAL level
            from supervisor import GateLevel
            self.assertEqual(escalated[0].level, GateLevel.CRITICAL)
            print("  ✓ test_09: Human Gate CRITICAL escalation on drift")

    print("=" * 60)
    print("BookGuardian — self-tests")
    print("=" * 60)
    unittest.main(module=__name__, argv=[""], exit=False, verbosity=0)
    print("=" * 60)


if __name__ == "__main__":
    import sys
    if "--watchdog" in sys.argv:
        path = sys.argv[sys.argv.index("--watchdog") + 1] if len(sys.argv) > sys.argv.index("--watchdog") + 1 else "docs/Ksiega_SYLION_3_4_FIXED.docx"
        run_watchdog(Path(path))
    else:
        _run_tests()
