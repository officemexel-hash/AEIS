"""Comprehensive RBAC matrix verification for SYLION AEIS v2 REST surface.

Goal: every v2 REST endpoint is exercised through two role contexts so we
detect regressions where a new route either (a) crashes the RBAC middleware
(``500``) or (b) is silently exempted from auth.

Two parametrized regression locks per route:

1. **No role header** — the request is sent without ``X-Sylion-Role`` /
   bearer token. The contract: never ``500``. In the default test
   environment ``SYLION_RBAC_DISABLED=1`` (set globally by
   ``tests/conftest.py``) so the actual response is usually ``200``/``4xx``;
   what matters is that the middleware does not blow up.

2. **Operator role** — same request with ``X-Sylion-Role: operator`` and
   ``Authorization: Bearer dev-bypass``. The contract: ``200`` or any
   ``4xx`` (validation, missing body, 404 for empty registries, etc.) but
   NEVER ``5xx``. A ``500`` from a route through the v2 plane means a route
   handler raised an unhandled exception in the happy-path smoke shape.

Skipped paths:

- Path templates with ``{...}`` placeholders — they need real ids and are
  covered by their own integration tests.
- ``/api/v1/terminal/stream`` — SSE streaming endpoint that holds the
  connection open forever; would deadlock the synchronous TestClient.
- ``/api/v1/terminal/_dev/inject_event`` — dev-only injection endpoint,
  covered by the terminal-suite integration tests.

The catalogue ``V2_ROUTES`` was generated by walking the v2 routers
(``federation_routes``, ``ontology_routes``, ``terminal_routes``,
``role_catalog_routes``, ``apps_routes``, ``policy_routes``,
``cron_routes``). The bookkeeping test
``test_v2_routes_catalogue_is_complete`` re-walks the routers at runtime
and skips with a clear message when somebody adds a new endpoint without
adding it here, so the matrix stays in sync without being a hard blocker
on new routes.
"""
