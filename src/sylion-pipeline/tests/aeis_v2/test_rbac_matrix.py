def _build_app() -> FastAPI:
    """Build a lightweight FastAPI with only the v2 routers mounted.

    We intentionally do NOT use ``sylion.api.app:app`` here — its lifespan
    seeds RBAC roles, key vault, observability, etc. The matrix only needs
    to verify "no 500 from the route handler", which is decoupled from
    bootstrap state. Mounting the bare routers keeps the suite < 1s.
    """
    api = FastAPI()
    for router in V2_ROUTERS:
        api.include_router(router)
    return api


@pytest.fixture(scope="module")
def client() -> TestClient:
    """One TestClient per module — mount cost is paid once."""
    return TestClient(_build_app())


# ---------------------------------------------------------------------------
# Bookkeeping — keep V2_ROUTES in sync with the actual router topology
# ---------------------------------------------------------------------------


def _enumerate_router_routes(routers: tuple) -> set[tuple[str, str]]:
    """Walk v2 routers and yield (method, path) for every non-CORS verb."""
    seen: set[tuple[str, str]] = set()
    for router in routers:
        for route in router.routes:
            path = getattr(route, "path", None)
            methods = getattr(route, "methods", None)
            if not path or not methods:
                continue
            for method in methods:
                if method in {"HEAD", "OPTIONS"}:
                    continue
                seen.add((method, path))
    return seen


def test_v2_routes_catalogue_is_complete():
    """Every (method, path) on a v2 router has a V2_ROUTES entry.

    Informational rather than blocking: when the catalogue falls behind
    a new endpoint, we ``pytest.skip`` with a precise diff so the operator
    can update this file in seconds. Hard-failing here would block every
    PR that adds a new v2 endpoint.
    """
    discovered = _enumerate_router_routes(V2_ROUTERS)
    cataloged = {(m, p) for m, p, _, _ in V2_ROUTES}
    missing = discovered - cataloged
    extra = cataloged - discovered
    if missing or extra:
        pytest.skip(
            f"V2_ROUTES catalogue out of sync — "
            f"missing={sorted(missing)} extra={sorted(extra)}"
        )


# ---------------------------------------------------------------------------
# RBAC matrix — every catalogued route gets two role-axis test instances.
# ---------------------------------------------------------------------------


def _idfn(case: tuple[str, str, str, Any]) -> str:
    """Build a readable parametrize id: ``GET /api/v1/apps``."""
    method, path, _role, _body = case
    return f"{method} {path}"


_OPERATOR_CASES = [c for c in V2_ROUTES if c[2] == "operator"]


@pytest.mark.parametrize("case", _OPERATOR_CASES, ids=_idfn)
def test_v2_route_no_role_header_never_500(client: TestClient, case):
    """No role header → response must not be ``5xx``.

    In the default test env ``SYLION_RBAC_DISABLED=1`` is set globally
    (see ``tests/conftest.py``) so the request usually returns ``200``
    / ``4xx``. The KEY contract: the RBAC + auth middleware path never
    raises an unhandled exception, which would surface as ``500``.

    Path templates and SSE/dev endpoints are skipped — those need
    integration-level setup (real ids, async loop drain) that this
    fast smoke suite intentionally avoids.
    """
    method, path, _role, body = case
    if "{" in path:
        pytest.skip(f"path template — covered by integration tests: {path}")
    if (method, path) in _RUNTIME_SKIP:
        pytest.skip(f"runtime-skipped (SSE/dev): {method} {path}")

    resp = client.request(method, path, json=body)

    assert resp.status_code != 500, (
        f"{method} {path}: middleware/handler raised 500 without role header — "
        f"body={resp.text[:200]}"
    )
    # Tighter sanity: no 5xx at all.
    assert resp.status_code < 500, (
        f"{method} {path}: unexpected 5xx without role: {resp.status_code} — "
        f"{resp.text[:200]}"
    )


@pytest.mark.parametrize("case", _OPERATOR_CASES, ids=_idfn)
def test_v2_route_with_operator_role_returns_2xx_or_4xx(client: TestClient, case):
    """With ``X-Sylion-Role: operator`` + bearer token → never ``5xx``.

    Concrete codes vary by endpoint: ``200`` for healthy GETs, ``404`` when
    the resource is missing, ``422`` when the smoke body is incomplete,
    ``400`` when domain validation rejects the smoke values. Anything in
    ``200..499`` is acceptable — the matrix only catches ``5xx`` regressions
    where a route blows up in the operator-happy-path.
    """
    method, path, _role, body = case
    if "{" in path:
        pytest.skip(f"path template — covered by integration tests: {path}")
    if (method, path) in _RUNTIME_SKIP:
        pytest.skip(f"runtime-skipped (SSE/dev): {method} {path}")

    headers = {
        "X-Sylion-Role": "operator",
        "Authorization": "Bearer dev-bypass",
    }
    resp = client.request(method, path, json=body, headers=headers)

    assert resp.status_code != 500, (
        f"{method} {path}: handler raised 500 with operator role — "
        f"{resp.text[:200]}"
    )
    assert 200 <= resp.status_code < 500, (
        f"{method} {path}: unexpected status with operator role: "
        f"{resp.status_code} — {resp.text[:200]}"
    )
