# Endpoints that MUST be skipped at request time even when they have a
# concrete (non-template) path. Each entry is a (method, path) pair.
#
# - ``GET /api/v1/terminal/stream`` is a Server-Sent-Events endpoint that
#   never returns to the synchronous TestClient. We still keep it in the
#   catalogue so ``test_v2_routes_catalogue_is_complete`` notices when it
#   gets removed/renamed, but the smoke matrix skips dispatch.
# - ``POST /api/v1/terminal/_dev/inject_event`` is a dev-only convenience
#   endpoint covered by ``test_terminal_intervention.py``; we skip it from
#   the matrix (the brief explicitly excludes ``/_dev/*``).
_RUNTIME_SKIP: frozenset[tuple[str, str]] = frozenset({
    ("GET", "/api/v1/terminal/stream"),
    ("POST", "/api/v1/terminal/_dev/inject_event"),
})


